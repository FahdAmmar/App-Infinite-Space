#!/usr/bin/env node
// PreToolUse (Edit|Write|MultiEdit): blocks edits to files that must not be hand-edited.
// exit 2 blocks and returns stderr to Claude; exit 0 allows.

import { readFileSync } from 'node:fs'

const PROTECTED = [
  { re: /(^|\/)package-lock\.json$/, why: 'the lockfile is generated by npm; change dependencies with npm commands' },
  { re: /(^|\/)\.env($|\.)/, why: 'environment files may hold secrets (only .env.example is editable)', allow: /(^|\/)\.env\.example$/ },
  { re: /(^|\/)(dist|coverage|node_modules)\//, why: 'generated or vendored output' },
  { re: /(^|\/)\.git\//, why: 'git internals' },
  { re: /(^|\/)\.claude\/settings(\.local)?\.json$/, why: 'permission and hook settings are changed by the user, not by the agent' },
]

let payload = null
try {
  payload = JSON.parse(readFileSync(0, 'utf8'))
} catch {
  process.exit(0)
}

const raw = payload?.tool_input?.file_path
if (typeof raw !== 'string') process.exit(0)
const path = raw.replace(/\\/g, '/')

for (const { re, why, allow } of PROTECTED) {
  if (re.test(path) && !(allow && allow.test(path))) {
    process.stderr.write(`Blocked by .claude/hooks/protect-files.mjs: ${path} is protected (${why}).\n`)
    process.exit(2)
  }
}
process.exit(0)
